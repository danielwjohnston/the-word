def subject_index():
    texts = {label(f): open(f, encoding='utf-8').read() for f in chapter_files()}
    out = ['# Subject Index {.unnumbered}\n', 'Entries point to the chapters and appendices where each subject is discussed substantively; the principal discussion is in bold. Generated by `tools/make_indexes.py` from a curated list of subjects.\n']
    for name, pat in sorted(SUBJECTS, key=lambda x: x[0].lower()):
        counts = {l: len(re.findall(pat, t, flags=re.I)) for l, t in texts.items()}
        counts = {l: c for l, c in counts.items() if c}
        if not counts: continue
        top = max(counts.values())
        keep = [l for l, c in counts.items() if c >= max(2, round(0.2 * top))] or [max(counts, key=counts.get)]
        principal = max(counts, key=counts.get)
        labs = [f'**{l}**' if l == principal else l for l in keep]
        out.append(f'**{name}**: {", ".join(labs)}  ')
    out.append('')
    open(os.path.join(ROOT, 'appendices', 'F-subject-index.md'), 'w', encoding='utf-8').write('\n'.join(out))

