#!/usr/bin/env python3
"""Generate the Scripture-and-ancient-sources index (Appendix E) and the subject index (Appendix F).
Markdown has no page numbers, so entries point to chapters."""
import os, re, glob, sys, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from audit import BOOKS

ORDER = ['GEN','EXO','LEV','NUM','DEU','JOS','JDG','RUT','1SA','2SA','1KI','2KI','1CH','2CH','EZR','NEH','EST','JOB','PSA','PRO','ECC','SNG','ISA','JER','LAM','EZK','DAN','HOS','JOL','AMO','OBA','JON','MIC','NAM','HAB','ZEP','HAG','ZEC','MAL',
         'MAT','MRK','LUK','JHN','ACT','ROM','1CO','2CO','GAL','EPH','PHP','COL','1TH','2TH','1TI','2TI','TIT','PHM','HEB','JAS','1PE','2PE','1JN','2JN','3JN','JUD','REV']
NAME = {'GEN':'Genesis','EXO':'Exodus','LEV':'Leviticus','NUM':'Numbers','DEU':'Deuteronomy','JOS':'Joshua','JDG':'Judges','1SA':'1 Samuel','2SA':'2 Samuel','1KI':'1 Kings','2KI':'2 Kings','1CH':'1 Chronicles','2CH':'2 Chronicles','NEH':'Nehemiah','JOB':'Job','PSA':'Psalms','PRO':'Proverbs','ISA':'Isaiah','JER':'Jeremiah','EZK':'Ezekiel','DAN':'Daniel','HOS':'Hosea','JOL':'Joel','AMO':'Amos','MIC':'Micah','HAB':'Habakkuk','ZEC':'Zechariah',
        'MAT':'Matthew','MRK':'Mark','LUK':'Luke','JHN':'John','ACT':'Acts','ROM':'Romans','1CO':'1 Corinthians','2CO':'2 Corinthians','GAL':'Galatians','EPH':'Ephesians','PHP':'Philippians','COL':'Colossians','1TH':'1 Thessalonians','2TH':'2 Thessalonians','1TI':'1 Timothy','2TI':'2 Timothy','TIT':'Titus','HEB':'Hebrews','JAS':'James','1PE':'1 Peter','2PE':'2 Peter','1JN':'1 John','JUD':'Jude','REV':'Revelation'}
APOC = {'Sir':'Sirach','Wis':'Wisdom of Solomon','3 Macc':'3 Maccabees'}

def label(fname):
    b = os.path.basename(fname)
    m = re.match(r'(\d\d)-jude', b)
    if m: return f'Ch. {int(m.group(1))}'
    return {'00b':'Reader\'s Intro','00c':'Method','00d':'Hist. Intro','00e':'Overview','14-afterword.md':'Afterword'}.get(b[:3] if b.startswith('00') else b, None) or \
           {'A':'App. A','B':'App. B','C':'App. C','D':'Glossary'}.get(b[0], b)

def chapter_files():
    fs = sorted(glob.glob(os.path.join(ROOT,'chapters','*.md'))) + sorted(glob.glob(os.path.join(ROOT,'appendices','[A-D]-*.md')))
    return [f for f in fs if not os.path.basename(f).startswith('00a')]

BOOK_RE = '|'.join(sorted((re.escape(k) for k in list(BOOKS)+list(APOC)), key=len, reverse=True))
REF = re.compile(r'(?<![\w])(' + BOOK_RE + r')\.?\s+(\d+(?::\d+)?(?:[–-]\d+(?::\d+)?)?(?:\s*[,;]\s*\d+(?::\d+)?(?:[–-]\d+)?(?!\s+[A-Z]))*)')

def scripture_index():
    idx = collections.defaultdict(lambda: collections.defaultdict(set))  # code -> ref -> labels
    for f in chapter_files():
        t = open(f, encoding='utf-8').read()
        t = re.sub(r'^\[\^[^\]]+\]:.*$', '', t, flags=re.M)
        lab = label(f)
        for m in REF.finditer(t):
            bk, nums = m.group(1), m.group(2)
            code = BOOKS.get(bk) or 'APOC:' + APOC[bk]
            ch = None
            for sep, piece in re.findall(r'(^|[,;])\s*([^,;]+)', nums):
                piece = piece.strip().replace('-', '–')
                if not piece: continue
                if ':' in piece:
                    ch = piece.split(':')[0]; ref = piece
                elif code == 'JUD' or ch is None or sep == ';':
                    ref = piece; ch = None if code != 'JUD' else ch
                else:
                    ref = f'{ch}:{piece}'
                idx[code][ref].add(lab)
        if re.match(r'\d\d-jude', os.path.basename(f)):
            for m in re.finditer(r'\(vv?\.\s*([\d–,\s-]+)\)', t):
                for piece in re.split(r'\s*,\s*', m.group(1).strip()):
                    if piece: idx['JUD'][piece.replace('-', '–')].add(lab)
    def sortkey(r):
        nums = [int(x) for x in re.findall(r'\d+', r)] + [0, 0]
        return nums[:2]
    out = ['# Index of Scripture and Ancient Sources {.unnumbered}\n',
           'References are to chapters ("Ch. 6"), the introductory chapters, and appendices. Generated by `tools/make_indexes.py` from the manuscript text.\n',
           '## Hebrew Bible, New Testament, and Apocrypha\n']
    for code in ORDER:
        if code not in idx: continue
        out.append(f'**{NAME.get(code, code)}**  ')
        parts = []
        for r in sorted(idx[code], key=sortkey):
            labs = sorted(idx[code][r], key=lambda x: (not x.startswith('Ch.'), int(re.sub(r'\D','',x) or 99) if x.startswith('Ch.') else 0, x))
            parts.append(f'{r} ({", ".join(labs)})')
        out.append('; '.join(parts) + '\n')
    for code in sorted(k for k in idx if k.startswith('APOC:')):
        out.append(f'**{code[5:]}**  ')
        out.append('; '.join(f'{r} ({", ".join(sorted(idx[code][r]))})' for r in sorted(idx[code], key=sortkey)) + '\n')
    # other ancient sources (curated patterns)
    ANC = [('1 Enoch', r'1 Enoch'), ('Testament of Naphtali', r'Testament of Naphtali'), ('Testament / Assumption of Moses', r'(Testament|Assumption|Ascension) of Moses'),
           ('Targum Pseudo-Jonathan / Jerusalem Targum', r'Targum'), ('Josephus', r'Josephus'), ('Philo', r'\bPhilo\b'), ('Dead Sea Scrolls / Qumran', r'Qumran|Dead Sea Scrolls|4Q20\d'),
           ('Mishnah, Avot', r'Mishnah'), ('Theophrastus, Characters', r'Theophrastus'), ('Pliny the Younger', r'\bPliny\b'), ('Didache', r'Didache'),
           ('Ignatius', r'Ignatius'), ('Clement of Alexandria', r'Clement of Alexandria|Clement'), ('Tertullian', r'Tertullian'), ('Origen', r'\bOrigen\b'),
           ('Hegesippus', r'Hegesippus'), ('Eusebius', r'Eusebius'), ('Muratorian Fragment', r'Muratorian'), ('Athanasius', r'Athanasius'), ('Jerome', r'\bJerome\b'),
           ('Augustine', r'Augustine'), ('Luther', r'\bLuther\b'), ('Calvin', r'\bCalvin\b')]
    out.append('## Other ancient and historical sources\n')
    texts = {label(f): open(f, encoding='utf-8').read() for f in chapter_files()}
    for name, pat in ANC:
        labs = [l for l, t in texts.items() if re.search(pat, t)]
        if labs: out.append(f'**{name}**: {", ".join(labs)}  ')
    out.append('')
    open(os.path.join(ROOT, 'appendices', 'E-scripture-index.md'), 'w', encoding='utf-8').write('\n'.join(out))

